"""Ledger of internal (unregistered) environment knobs the backend reads.

``constants/settings_registry.json`` is the authoritative registry for
managed and public settings. It cannot carry an internal knob: a registered
``fastapi.runtime`` integer or number is coerced by
``RuntimeSettings.from_sources`` at snapshot time, so a malformed value would
fail process start, and every registered name becomes visible to the admin
settings endpoint. The names below are operator/developer knobs that are
read only through the accessor API in ``utils/get_env.py`` and
``utils/env_settings/`` and are deliberately kept out of the registry, the
compose files and the README.

``tests/unit/test_internal_env_names.py`` asserts that every name an
accessor reads is either registered or listed here, and that nothing listed
here has gone stale. Add a one-line purpose when you add a name.
"""


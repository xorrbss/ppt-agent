"""Google image provider adapter used by the image-generation facade."""

from __future__ import annotations

import asyncio
import base64
import os
from collections.abc import Callable
from pathlib import Path
from typing import Any
import uuid

from fastapi import HTTPException


async def generate_google_image(
    prompt: str,
    output_directory: str,
    model: str,
    *,
    api_key: str | None,
    client_factory: Callable[..., Any],
    config_factory: Callable[..., Any],
) -> str:
    """Generate one image while keeping provider SDK details behind an adapter."""
    if not api_key:
        raise ValueError("GOOGLE_API_KEY is not configured")
    client = client_factory(api_key=api_key)
    response = await asyncio.to_thread(
        client.models.generate_content,
        model=model,
        contents=prompt,
        config=config_factory(response_modalities=["IMAGE"]),
    )

    response_parts = getattr(response, "parts", None)
    if not response_parts and getattr(response, "candidates", None):
        first_candidate = response.candidates[0] if response.candidates else None
        content = getattr(first_candidate, "content", None) if first_candidate else None
        response_parts = getattr(content, "parts", None) if content else None

    image_path = None
    for part in response_parts or []:
        if part.inline_data is None:
            continue
        mime_type = getattr(part.inline_data, "mime_type", "") or ""
        ext = mime_type.split("/")[-1] if mime_type.startswith("image/") else "png"
        image_path = os.path.join(output_directory, f"{uuid.uuid4()}.{ext}")
        if hasattr(part, "as_image"):
            part.as_image().save(image_path)
            continue
        image_data = getattr(part.inline_data, "data", None)
        if image_data is None:
            image_path = None
            continue
        image_bytes = (
            base64.b64decode(image_data)
            if isinstance(image_data, str)
            else image_data
        )
        await asyncio.to_thread(Path(image_path).write_bytes, image_bytes)

    if not image_path:
        raise HTTPException(
            status_code=500,
            detail=f"No image generated by google {model}",
        )
    return image_path


__all__ = ["generate_google_image"]

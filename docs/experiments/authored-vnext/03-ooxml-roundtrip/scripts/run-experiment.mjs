import { access, mkdir } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import {
  FacadePolicyError,
  createSyntheticDeck,
  inspectPolicy,
  openDocument,
  writeJson,
} from '../src/genoffice-facade.mjs'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const experimentRoot = resolve(scriptDir, '..')
const repositoryRoot = resolve(experimentRoot, '..', '..', '..', '..')
const artifactsDir = join(experimentRoot, 'artifacts')
const resultsDir = join(experimentRoot, 'results')

const defaultExisting90 = join(
  repositoryRoot,
  '.codex-tmp',
  'export-audit-dfec1e94',
  'original-export.pptx',
)
const realCorpus = [
  'docs/artifacts/ppt-master-catalog/ppt-master-ai-technology-proposal.pptx',
  'docs/artifacts/ppt-master-catalog/ppt-master-business-proposal.pptx',
  'docs/artifacts/ppt-master-catalog/ppt-master-data-analysis-report.pptx',
  'docs/artifacts/ppt-master-catalog/ppt-master-executive-report.pptx',
  'docs/artifacts/ppt-master-catalog/ppt-master-project-performance-report.pptx',
  'docs/artifacts/ppt-master-data-journalism/ai-capital-2026-data-journalism.pptx',
].map((relative) => join(repositoryRoot, relative))

function argValue(name) {
  const index = process.argv.indexOf(name)
  return index >= 0 ? process.argv[index + 1] : undefined
}

async function exists(path) {
  try {
    await access(path)
    return true
  } catch {
    return false
  }
}

async function capture(operation, callback) {
  const startedAt = new Date().toISOString()
  const start = performance.now()
  try {
    const value = await callback()
    return {
      operation,
      status: 'completed',
      startedAt,
      durationMs: Math.round(performance.now() - start),
      value,
    }
  } catch (error) {
    return {
      operation,
      status: 'failed',
      startedAt,
      durationMs: Math.round(performance.now() - start),
      error: {
        name: error?.name ?? 'Error',
        code: error instanceof FacadePolicyError ? error.code : undefined,
        message: error?.message ?? String(error),
        evidence: error instanceof FacadePolicyError ? error.evidence : undefined,
      },
    }
  }
}

await mkdir(artifactsDir, { recursive: true })
await mkdir(resultsDir, { recursive: true })

const existing90 = resolve(argValue('--existing90') ?? defaultExisting90)
const synthetic90 = join(artifactsDir, 'synthetic-90.pptx')
const operations = []

operations.push(
  await capture('synthetic-90:create', () => createSyntheticDeck(synthetic90, 90)),
)
operations.push(
  await capture('synthetic-90:no-op', async () => {
    const session = await openDocument(synthetic90)
    return session.saveNoop(join(artifactsDir, 'synthetic-90-noop.pptx'))
  }),
)

const existing90Available = await exists(existing90)
if (existing90Available) {
  operations.push(
    await capture('existing-90:policy', () => inspectPolicy(existing90)),
    await capture('existing-90:no-op', async () => {
      const session = await openDocument(existing90)
      return session.saveNoop(join(artifactsDir, 'existing-90-noop.pptx'))
    }),
    await capture('existing-90:targeted-text-edit', async () => {
      const session = await openDocument(existing90)
      return session.saveTargetedTextEdit(join(artifactsDir, 'existing-90-text-edit.pptx'))
    }),
    await capture('existing-90:master-crud', async () => {
      const session = await openDocument(existing90)
      const capabilities = session.masterCrudCapabilities()
      const update = await session.saveMasterNameProbe(join(artifactsDir, 'existing-90-master-update.pptx'))
      return { capabilities, update }
    }),
  )
}

for (const corpusPath of realCorpus) {
  const stem = corpusPath.slice(corpusPath.lastIndexOf('\\') + 1, -5)
  operations.push(
    await capture(`real-corpus:${stem}:no-op`, async () => {
      const session = await openDocument(corpusPath)
      return session.saveNoop(join(artifactsDir, `real-${stem}-noop.pptx`))
    }),
  )
}

const report = {
  schemaVersion: 1,
  generatedAt: new Date().toISOString(),
  adapter: {
    upstream: 'https://github.com/genspark-ai/genoffice',
    pin: 'dc4d7e5927864498913b7ba42d0da06cc7cf628e',
    boundary: 'packages/pptx-engine only',
  },
  corpus: {
    existing90: {
      path: existing90,
      available: existing90Available,
      classification:
        'local ignored Presenton-generated artifact; blank metadata; no external transmission; provenance not Git-tracked',
    },
    synthetic90: {
      path: synthetic90,
      classification: 'new synthetic deck generated by the isolated GenOffice engine',
    },
    realCorpus: realCorpus.map((path) => ({
      path,
      classification: 'Git-tracked project artifact',
    })),
  },
  operations,
}

await writeJson(join(resultsDir, 'operation-results.json'), report)
console.log(JSON.stringify({ result: join(resultsDir, 'operation-results.json'), operations }, null, 2))
if (operations.some((operation) => operation.status === 'failed')) process.exitCode = 1
